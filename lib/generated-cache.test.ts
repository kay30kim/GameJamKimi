import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, readFile, readdir, rm, stat } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createGeneratedCache, diskGeneratedStorage, generatedCacheBackend, generatedKey, readGenerated, writeGenerated } from "./generated-cache";
import type { GeneratedStorage } from "./generated-cache";

const bytes = (text: string) => new TextEncoder().encode(text);
const key = (value: unknown) => generatedKey(["test-v1", value]);

test("canonical keys ignore object order but isolate full branch and speech identity", () => {
  assert.equal(key({ language: "ko", age: 4 }), key({ age: 4, language: "ko" }));
  assert.notEqual(key({ age: 4 }), key({ age: 5 }));
  assert.notEqual(key({ choices: ["help", "leave"] }), key({ choices: ["leave", "help"] }));
  assert.notEqual(key({ continuation: { holder: "hero" } }), key({ continuation: { holder: "friend" } }));
  assert.notEqual(key({ text: "안녕", voice: "hero" }), key({ text: "안녕", voice: "duck" }));
  assert.match(key("private child story"), /^[a-f0-9]{64}$/);
  assert.equal(key({ omitted: undefined }), key({}));
});

test("a new cache instance reads the same generated bytes from persistent disk", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "alicetales-generated-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const first = createGeneratedCache(diskGeneratedStorage(directory));
  const id = key("persistent narration");
  assert.equal(await first.read("tts", id), null);
  assert.equal(await first.write("tts", id, bytes("MP3-bytes"), "audio/mpeg"), true);
  const nextProcess = createGeneratedCache(diskGeneratedStorage(directory));
  assert.deepEqual(await nextProcess.read("tts", id), bytes("MP3-bytes"));
  const file = join(directory, "generated/v1/tts", `${id}.mp3`);
  assert.deepEqual(await readFile(file), Buffer.from("MP3-bytes"));
  assert.equal((await stat(file)).mode & 0o777, 0o600);
  assert.deepEqual(await readdir(join(directory, "generated/v1/tts")), [`${id}.mp3`]);
});

test("read and write failures fail open without leaking provider errors", async () => {
  const failure: GeneratedStorage = {
    read: async () => { throw new Error("private upstream payload"); },
    write: async () => { throw new Error("private upstream payload"); },
  };
  const cache = createGeneratedCache(failure);
  const id = key("outage");
  assert.equal(await cache.read("scene", id), null);
  assert.equal(await cache.write("scene", id, bytes('{"valid":true}'), "application/json"), false);
  // A failed persistent write must not masquerade as a prepared artifact later.
  assert.equal(await cache.read("scene", id), null);
});

test("hard deadlines abort unresponsive storage instead of blocking generation", async () => {
  const signals: AbortSignal[] = [];
  const hanging: GeneratedStorage = {
    read: (_path, signal) => { signals.push(signal); return new Promise(() => {}); },
    write: (_path, _bytes, _type, signal) => { signals.push(signal); return new Promise(() => {}); },
  };
  const cache = createGeneratedCache(hanging, { readTimeoutMs: 10, writeTimeoutMs: 10 });
  assert.equal(await cache.read("tts", key("timeout")), null);
  assert.equal(await cache.write("tts", key("timeout"), bytes("audio"), "audio/mpeg"), false);
  assert.equal(signals.length, 2);
  assert.ok(signals.every((signal) => signal.aborted));
});

test("memory byte and entry bounds evict the least recently used item", async () => {
  const cache = createGeneratedCache(null, { maxBytes: 6, maxEntries: 2 });
  await cache.write("tts", key("a"), bytes("aa"), "audio/mpeg");
  await cache.write("tts", key("b"), bytes("bb"), "audio/mpeg");
  await cache.read("tts", key("a"));
  await cache.write("tts", key("c"), bytes("ccc"), "audio/mpeg");
  assert.deepEqual(await cache.read("tts", key("a")), bytes("aa"));
  assert.equal(await cache.read("tts", key("b")), null);
  assert.deepEqual(await cache.read("tts", key("c")), bytes("ccc"));
});

test("cached buffers are copied so a caller cannot corrupt later responses", async () => {
  const cache = createGeneratedCache(null);
  const id = key("copy");
  const input = Buffer.from("original");
  await cache.write("tts", id, input, "audio/mpeg");
  input[0] = 0;
  const first = (await cache.read("tts", id))!;
  first[1] = 0;
  assert.deepEqual(await cache.read("tts", id), bytes("original"));
});

test("empty, oversized, wrong-type and path traversal entries are never stored", async () => {
  let writes = 0;
  const cache = createGeneratedCache({ read: async () => null, write: async () => { writes++; } });
  assert.equal(await cache.write("tts", "../outside", bytes("audio"), "audio/mpeg"), false);
  assert.equal(await cache.read("scene", "../../secret"), null);
  assert.equal(await cache.write("scene", key("type"), bytes("audio"), "audio/mpeg"), false);
  assert.equal(await cache.write("tts", key("empty"), new Uint8Array(), "audio/mpeg"), false);
  assert.equal(await cache.write("tts", key("huge"), new Uint8Array(8 * 1024 * 1024 + 1), "audio/mpeg"), false);
  assert.equal(writes, 0);
});

test("empty or oversized storage responses are cache misses", async () => {
  for (const payload of [new Uint8Array(), new Uint8Array(8 * 1024 * 1024 + 1)]) {
    const cache = createGeneratedCache({ read: async () => payload, write: async () => {} });
    assert.equal(await cache.read("tts", key("bad size")), null);
  }
});

test("explicitly disabling storage prevents disk, Blob and memory reuse", async (t) => {
  const old = process.env.GENERATED_CACHE_DISABLED;
  t.after(() => { if (old === undefined) delete process.env.GENERATED_CACHE_DISABLED; else process.env.GENERATED_CACHE_DISABLED = old; });
  process.env.GENERATED_CACHE_DISABLED = "1";
  assert.equal(generatedCacheBackend(), "disabled");
  assert.equal(await writeGenerated("scene", key("disabled"), bytes("{}"), "application/json"), false);
  assert.equal(await readGenerated("scene", key("disabled")), null);
});
